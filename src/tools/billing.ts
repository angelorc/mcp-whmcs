import { z } from 'zod';
import { date, defineTool, id, invoiceItem, pagination, type ToolDef } from './types.js';

const invoiceId = { invoiceid: id('Invoice ID') };

const invoiceStatus = z.enum([
  'Draft',
  'Unpaid',
  'Paid',
  'Cancelled',
  'Refunded',
  'Collections',
  'Payment Pending',
]);

const quoteLineItem = z.object({
  desc: z.string(),
  qty: z.number().default(1),
  up: z.number().describe('Unit price'),
  discount: z.number().optional().describe('Discount percentage'),
  taxable: z.boolean().optional(),
});

const quoteFields = {
  subject: z.string().optional(),
  stage: z.enum(['Draft', 'Delivered', 'On Hold', 'Accepted', 'Lost', 'Dead']).optional(),
  validuntil: date('Valid until').optional(),
  datecreated: date('Creation date').optional(),
  userid: id('Client ID').optional(),
  lineitems: z.array(quoteLineItem).optional(),
  proposal: z.string().optional(),
  customernotes: z.string().optional(),
  adminnotes: z.string().optional(),
};

